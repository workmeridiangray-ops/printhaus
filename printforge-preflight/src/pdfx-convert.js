const fs = require('fs');
const path = require('path');
const { execFile } = require('child_process');
const { COLOUR_PROFILES } = require('./formats');

const PROFILES_DIR = path.join(__dirname, '..', 'profiles');
// Only FOGRA39 is a real bundled ICC file today. Europe/USA fall back to it
// (see formats.js COLOUR_PROFILES for the honest "real: false" flag) rather
// than silently mislabeling output — swap in FOGRA51.icc / GRACoL2013.icc
// here once they're sourced and added to profiles/.
const PROFILE_FILES = {
  universal: path.join(PROFILES_DIR, 'FOGRA39.icc'),
  europe: path.join(PROFILES_DIR, 'FOGRA39.icc'),
  usa: path.join(PROFILES_DIR, 'FOGRA39.icc'),
};

/**
 * Runs the intermediate PDF (RGB raster + vector crop marks) through
 * Ghostscript, converting it to a genuine PDF/X-1a:2001 file:
 *  - forces DeviceCMYK process color (no RGB left anywhere)
 *  - embeds the chosen ICC profile as the OutputIntent
 *  - sets GTS_PDFXVersion / GTS_PDFXConformance so a press's RIP sees
 *    a real PDF/X-1a file, not just a PDF with the right colors
 */
async function convertToPdfX1a({ inputPdfPath, outputPdfPath, title, colourProfile = 'universal', colourSpace = 'cmyk' }) {
  const profile = COLOUR_PROFILES[colourProfile] || COLOUR_PROFILES.universal;
  const iccPath = PROFILE_FILES[colourProfile] || PROFILE_FILES.universal;
  const isCmyk = colourSpace !== 'rgb';

  // RGB mode matches PrintGo's "screen-based, for on-screen use" option: it's
  // a real choice, not a disabled toggle, but PDF/X-1a *requires* CMYK by
  // definition (ISO 15930-1), so picking RGB here deliberately produces a
  // plain, non-PDF/X PDF rather than a mislabeled one.
  const defScriptPath = outputPdfPath + '.PDFX_def.ps';
  if (isCmyk) {
    fs.writeFileSync(defScriptPath, buildPdfxDefScript({ title, iccPath, profile }));
  }

  const args = [
    // NOSAFER: this script and its inputs are all generated by this pipeline
    // itself (never raw user-supplied PostScript), so Ghostscript's SAFER
    // sandbox — which on some platforms (notably newer macOS builds) also
    // blocks Ghostscript's own temp-file writes — is disabled here rather
    // than worked around file-by-file.
    '-dNOSAFER',
    ...(isCmyk ? [`--permit-file-read=${iccPath}`, '-dPDFX'] : []),
    '-dBATCH',
    '-dNOPAUSE',
    '-dNOOUTERSAVE',
    '-dCompatibilityLevel=1.3',
    `-sColorConversionStrategy=${isCmyk ? 'CMYK' : 'RGB'}`,
    `-sProcessColorModel=${isCmyk ? 'DeviceCMYK' : 'DeviceRGB'}`,
    '-dPDFSETTINGS=/prepress',
    '-dDownsampleColorImages=false',
    '-dDownsampleGrayImages=false',
    '-dDownsampleMonoImages=false',
    '-sDEVICE=pdfwrite',
    `-sOutputFile=${outputPdfPath}`,
    ...(isCmyk ? [defScriptPath] : []),
    inputPdfPath,
  ];

  await new Promise((resolve, reject) => {
    execFile('gs', args, { maxBuffer: 1024 * 1024 * 20 }, (err, stdout, stderr) => {
      if (!err && isCmyk) fs.unlinkSync(defScriptPath);
      if (err) {
        return reject(new Error(`Ghostscript failed: ${stderr || err.message}`));
      }
      resolve({ stdout, stderr });
    });
  });

  return { outputPdfPath, profileUsed: profile, colourSpace: isCmyk ? 'cmyk' : 'rgb', isPdfX: isCmyk };
}

function buildPdfxDefScript({ title, iccPath, profile }) {
  const safeTitle = (title || 'PrintForge Press-Ready File').replace(/[()\\]/g, '');
  return `%!
/pdfmark where not {userdict /pdfmark /cleartomark load put} if

[ /Title (${safeTitle})
  /DOCINFO pdfmark

[ /GTS_PDFXVersion (PDF/X-1a:2001)
  /GTS_PDFXConformance (PDF/X-1a:2001)
  /Trapped /False
  /DOCINFO pdfmark

[ /_objdef {icc_PDFX} /type /stream /OBJ pdfmark
[ {icc_PDFX} <<
  /N 4
  >> /PUT pdfmark
[ {icc_PDFX} (${iccPath.replace(/\\/g, '\\\\')}) (r) file /PUT pdfmark

[ /_objdef {OutputIntent_PDFX} /type /dict /OBJ pdfmark
[ {OutputIntent_PDFX} <<
  /Type /OutputIntent
  /S /GTS_PDFX
  /DestOutputProfile {icc_PDFX}
  /OutputConditionIdentifier (${profile.standard})
  /OutputCondition (Commercial offset, coated paper)
  /RegistryName (http://www.color.org)
  /Info (${profile.standard})
  >> /PUT pdfmark
[ {Catalog} <<
  /OutputIntents [ {OutputIntent_PDFX} ]
  >> /PUT pdfmark
`;
}

module.exports = { convertToPdfX1a, PROFILE_FILES };
